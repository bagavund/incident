<?php

namespace App\Models\Concerns;

/**
 * Небольшой справочник, редактируемый в админке.
 *
 * Инциденты ссылаются на значения этих справочников по названию (кроме
 * сервисов — там pivot по id), поэтому переименование обязано протащить новое
 * название во все инциденты: иначе ссылки осиротеют, фильтры перестанут
 * находить, а валидация `exists` уронит следующее сохранение инцидента.
 */
interface LookupValue
{
    /** Сколько инцидентов ссылаются на это значение. */
    public function usageCount(): int;

    /** Переносит ссылки инцидентов со старого названия на новое. */
    public function renameUsagesTo(string $newName): void;
}
